/**
 * overview.mjs - demos/index.html: every launch demo with its hero image and one metrics line, from each demo's
 * summary.json (written by report.mjs).
 *
 *     node demos/shared/overview.mjs
 */
import {existsSync, readFileSync, writeFileSync} from 'node:fs'

const DEMOS = ['camera', 'haussmann', 'stair', 'edit-chain', 'house-walkthrough', 'geometry-nodes']
const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;'})[c])
const cards = DEMOS.map(n => {
    const f = `demos/${n}/summary.json`
    if (!existsSync(f)) return `<a class="card missing" href="${n}/index.html"><div class="img"></div><h2>${n}</h2><p>not recorded yet</p></a>`
    const s = JSON.parse(readFileSync(f, 'utf8'))
    return `<a class="card" href="${n}/index.html">${s.hero ? `<img src="${n}/${s.hero}" alt="${esc(s.title)}">` : '<div class="img"></div>'}<h2>${esc(s.title)}</h2><p>${esc(s.blurb)}</p><div class="line">${esc(s.line)}</div></a>`
}).join('\n')
const renderers = [...new Set(DEMOS.map(n => `demos/${n}/summary.json`).filter(existsSync).map(f => JSON.parse(readFileSync(f, 'utf8')).renderer))]
writeFileSync('demos/index.html', `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>threepipe modelling - launch demos</title>
<style>
body { margin: 0; background: #0f1012; color: #ececee; font: 16px/1.55 Inter, ui-sans-serif, system-ui, -apple-system, sans-serif }
main { max-width: 1280px; margin: 0 auto; padding: 40px 24px 80px }
h1 { font-weight: 300; font-size: 46px; margin: 8px 0 }
.kick { font: 600 13px ui-monospace, Menlo, monospace; letter-spacing: .2em; text-transform: uppercase; color: #c0101c }
.intro { color: #c9cad0; max-width: 900px; font-size: 18px }
.grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(380px, 1fr)); gap: 22px; margin-top: 30px }
.card { display: block; color: inherit; text-decoration: none; background: #17181b; border: 1px solid #26282d; border-radius: 8px; overflow: hidden; transition: border-color .15s }
.card:hover { border-color: #55575e } .card img, .card .img { width: 100%; aspect-ratio: 16 / 9; object-fit: cover; display: block; background: #222 }
.card h2 { font-weight: 500; font-size: 21px; margin: 14px 16px 4px } .card p { margin: 0 16px; color: #a6a8b0; font-size: 15px }
.card .line { margin: 10px 16px 16px; font: 13px ui-monospace, Menlo, monospace; color: #d6d7db }
.foot { color: #8a8c94; font-size: 13px; margin-top: 30px }
</style></head><body><main>
<div class="kick">threepipe · modelling · launch</div>
<h1>Launch demos</h1>
<p class="intro">Six demos of threepipe's modelling tools, rebuilt against the current editor and filmed on a GPU: a camera and two buildings built through the JSON command API with the realism kit, a 30-step edit chain scored for locality and undo, the editor driven with a real keyboard and mouse, and Blender geometry nodes edited live in the modifier panel. Each page has the film (not committed: video.mp4 next to it), key stills, metrics and how it was made.</p>
<div class="grid">
${cards}
</div>
<p class="foot">Rendered on ${renderers.map(esc).join('; ')}. Generated by demos/shared/overview.mjs.</p>
</main></body></html>
`)
