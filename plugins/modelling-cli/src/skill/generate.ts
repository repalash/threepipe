/**
 * `SKILL.md` and the Claude Code plugin manifest, generated from the command registry and the cookbook.
 *
 * Generated, not written: the command reference is `describeCommands()`, the examples are the cookbook
 * the tests run, and `tests/skill.test.ts` fails when the committed file differs from what this writes -
 * so the skill cannot describe a command that changed.
 */

import {COOKBOOK, RULES} from './cookbook'

export interface SkillCommandInfo {
    name: string
    description: string
    inputSchema: {properties: Record<string, any>, required?: string[]}
    group: string
    mutates: boolean
}

const GROUP_ORDER = ['create', 'edit', 'shape', 'loop', 'cut', 'fill', 'modifiers', 'scene', 'reference', 'session', 'look', 'checks', 'import']

function typeOf(spec: any): string {
    if (!spec) return 'any'
    if (spec.enum) return spec.enum.map((v: string) => `"${v}"`).join(' | ')
    if (spec.oneOf) return spec.oneOf.map(typeOf).join(' | ')
    if (spec.type === 'array') return spec.minItems === 3 && spec.maxItems === 3 ? '[x, y, z]' : `${typeOf(spec.items)}[]`
    return spec.type ?? 'any'
}

function params(c: SkillCommandInfo): string {
    const req = new Set(c.inputSchema.required ?? [])
    const names = Object.keys(c.inputSchema.properties)
    if (!names.length) return '-'
    return names.map(n => `\`${n}${req.has(n) ? '' : '?'}\`: ${typeOf(c.inputSchema.properties[n])}`).join(', ')
}

export function renderSkill(commands: SkillCommandInfo[], version: string): string {
    const byGroup = new Map<string, SkillCommandInfo[]>()
    for (const c of commands) byGroup.set(c.group, [...byGroup.get(c.group) ?? [], c])
    const rank = (g: string) => GROUP_ORDER.includes(g) ? GROUP_ORDER.indexOf(g) : GROUP_ORDER.length
    const groups = [...byGroup.keys()].sort((a, b) => rank(a) - rank(b) || a.localeCompare(b))
    const out: string[] = []
    out.push('---')
    out.push('name: threepipe-modelling')
    out.push('description: Build and edit 3D models (editable n-gon meshes) with threepipe\'s modelling command API - through the '
        + 'threepipe-modelling MCP tools, the `threepipe-modelling` CLI, or a live editor on the agent socket. Use when asked to model, '
        + 'block out, edit, measure, validate, render or export 3D geometry, or to make a generated model editable.')
    out.push('---')
    out.push('')
    out.push('# threepipe modelling')
    out.push('')
    out.push(`<!-- Generated by \`npm run modelling:skill\` from @threepipe/plugin-modelling ${version} (${commands.length} commands). `
        + 'Do not edit by hand: change the command definitions or plugins/modelling-cli/src/skill/, and regenerate. '
        + 'Every example below is run by plugins/modelling-cli/tests/skill.test.ts. -->')
    out.push('')
    out.push('A document of named objects, each an editable polygon mesh (n-gons, Blender\'s BMesh ported to TypeScript), '
        + 'changed only by JSON commands `{op, ...params}`. The same commands reach it three ways:')
    out.push('')
    out.push('- **MCP** (`@threepipe/modelling-mcp`): tools `run`, `batch`, `look`, `measure`, `validate`, `diff`, `inspect`, '
        + '`export`, `help`, `enableToolGroup`. `run` offers some groups; `enableToolGroup` adds more.')
    out.push('- **CLI** (`npx threepipe-modelling <verb>`): `run`, `session`, `look`, `measure`, `validate`, `diff`, `inspect`, '
        + '`export`, `import`, `help`, `relay`. Each prints one JSON object; `--doc model.glb` keeps the document between calls.')
    out.push('- **Agent socket**: a live editor connected to the MCP server or `threepipe-modelling relay` (`?agent=…&agentToken=…`, '
        + 'or File > Connect Agent…). Your commands run in the person\'s editor and land in its undo history; `help` says where you are.')
    out.push('')
    out.push('## Workflow')
    out.push('')
    out.push('0. **Measure, then block out**: for a real object, first write down its numbers from public sources - published '
        + 'dimensions, standard interfaces (lens mounts, threads, ISO sizes) and photographs placed to scale with `reference '
        + '{calibrate}` - each with its unit, source and uncertainty. Block the main masses to them as low-poly cages under '
        + '`subsurf`, then check the silhouettes: `camera {view: "ref:<name>"}` and `look` with the photo behind at `opacity` 0.5. '
        + 'An outline that misses the photo goes back to the cage; detail only after the masses fit.')
    out.push('1. **Build** with `run` / `batch`: create, then edit. Name everything.')
    out.push('2. **Measure**: `measure` (bounds, overlaps, `mode: "topology"`) and `inspect`.')
    out.push('3. **Validate**: `validate` (Blender\'s `BM_mesh_is_valid` + a `spec` of the dimensions you were given).')
    out.push('4. **Look**: `look` - an image *and* a description of what is in it. Last, not first.')
    out.push('5. **Export**: `export` a GLB.')
    out.push('')
    out.push('Guarantees: a command either completes or changes nothing; every mutating command is one undo step and reports '
        + '`changed` and `locality` (what it changed, split into what it named and collateral); replaying the same commands '
        + 'gives the same model file. Errors come back as `{ok: false, error}` with a "did you mean" when it is a name.')
    out.push('')
    out.push('## Rules')
    out.push('')
    for (const r of RULES) out.push(`- ${r}`)
    out.push('')
    out.push('## Cookbook')
    out.push('')
    for (const e of COOKBOOK) {
        out.push(`### ${e.task}`)
        out.push('')
        out.push(e.how)
        out.push('')
        if (e.given?.length) {
            out.push('Given:')
            out.push('')
            out.push('```json')
            for (const c of e.given) out.push(JSON.stringify(c))
            out.push('```')
            out.push('')
        }
        out.push('```json')
        for (const c of e.commands) out.push(JSON.stringify(c))
        out.push('```')
        out.push('')
    }
    out.push('## Commands')
    out.push('')
    out.push('`?` marks optional parameters. `help {command: "<op>"}` (MCP: `help {op}`) gives the full description and schema. '
        + 'Object references take a name, a list, `prefix*` or `*`; index lists take `[1, 2]` or `{from, to}`.')
    out.push('')
    for (const g of groups) {
        out.push(`### ${g}`)
        out.push('')
        out.push('| op | does | parameters |')
        out.push('| --- | --- | --- |')
        for (const c of byGroup.get(g)!.sort((a, b) => a.name.localeCompare(b.name))) {
            out.push(`| \`${c.name}\`${c.mutates ? '' : ' (read-only)'} | ${c.description.split('\n')[0].replace(/\|/g, '\\|')} | ${params(c).replace(/\|/g, '\\|')} |`)
        }
        out.push('')
    }
    return out.join('\n')
}

/** `.claude-plugin/plugin.json` for the repository as a Claude Code plugin: the skill plus the MCP server. */
export function renderPluginManifest(version: string): string {
    return JSON.stringify({
        name: 'threepipe-modelling',
        version,
        description: 'Model and edit 3D geometry with threepipe: an MCP server over the modelling command API (live editor or headless) and a skill with the workflow, rules and a tested cookbook.',
        author: {name: 'repalash', email: 'palash@shaders.app'},
        homepage: 'https://threepipe.org/guide/connect-an-agent.html',
        repository: 'https://github.com/repalash/threepipe',
        license: 'Apache-2.0',
        keywords: ['3d', 'modelling', 'mesh', 'threepipe', 'three.js', 'mcp'],
        mcpServers: {
            'threepipe-modelling': {command: 'npx', args: ['-y', '@threepipe/modelling-mcp']},
        },
    }, null, 2) + '\n'
}

/** `.claude-plugin/marketplace.json`: `/plugin marketplace add repalash/threepipe`, then install `threepipe-modelling`. */
export function renderMarketplace(version: string): string {
    return JSON.stringify({
        name: 'threepipe',
        owner: {name: 'repalash', email: 'palash@shaders.app'},
        plugins: [{
            name: 'threepipe-modelling',
            source: './',
            version,
            description: 'threepipe modelling: MCP server + skill for building and editing 3D meshes.',
        }],
    }, null, 2) + '\n'
}
