"""
vendor_results.py - copy run_cases.py results into the package as compact parity fixtures.

Usage (plain Python, no Blender): python3 vendor_results.py <run_cases out dir> <fixture dir>
Keeps {"blender", "hash", "geometry", "scene"?, "input"?} of every <case id>.json (the case itself is regenerated by the tests,
the input geometry is not compared), written without indentation. Cases Blender failed on are not copied.
"""

import json
import os
import shutil
import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    os.makedirs(dst)
    copied = 0
    for name in sorted(os.listdir(src)):
        if not name.endswith(".json"):
            continue
        with open(os.path.join(src, name), encoding="utf8") as handle:
            result = json.load(handle)
        if "error" in result:
            print(f"skipped {name}: {result['error']}")
            continue
        with open(os.path.join(dst, name), "w", encoding="utf8") as handle:
            kept = {"blender": result["blender"], "hash": result["hash"], "geometry": result["geometry"]}
            if result.get("scene"):
                kept["scene"] = result["scene"]
            # The modifier's input geometry, when the case starts from a mesh (not "empty").
            if result.get("input") and result["case"].get("input", "empty") != "empty":
                kept["input"] = result["input"]
            json.dump(kept,
                      handle, separators=(",", ":"), allow_nan=True)
        binary = os.path.join(src, name[:-5] + ".bin")
        if os.path.exists(binary) and os.path.getsize(binary):
            shutil.copy(binary, os.path.join(dst, name[:-5] + ".bin"))
        copied += 1
    print(f"{copied} results in {dst}")


main()
