/**
 * String function nodes (`nodes/function/nodes/node_fn_*_string.cc`, `node_fn_string_length.cc`,
 * `node_fn_value_to_string.cc`, `node_fn_input_string.cc`, `node_fn_input_special_characters.cc`) and Join Strings
 * (`node_geo_string_join.cc`).
 *
 * Strings are single values. Blender's strings are UTF-8 bytes; the strings here are JS strings of whole code points
 * (valid UTF-8), so Blender's UTF-8 walks (`BLI_strlen_utf8`, `BLI_str_utf8_offset_from_index`,
 * `BLI_str_find_prev_char_utf8`) are code-point walks, and byte positions (`StringRef::find`) are converted.
 */

import {registerNodeType} from '../../runtime/registry'
import type {ExecParams} from '../../runtime/params'
import {GField} from '../../fields/field'

const encoder = new TextEncoder()
const decoder = new TextDecoder()

/** Code points of a string (`BLI_str_utf8_as_utf32`). */
const codePoints = (s: string) => Array.from(s)

const int = (v: number) => GField.constant('int32', [v])
const bool = (v: boolean) => GField.constant('bool', [v ? 1 : 0])

function stringNode(idname: string, label: string, declare: Parameters<typeof registerNodeType>[0]['declare'],
    execute: (p: ExecParams) => void, extra: Partial<Parameters<typeof registerNodeType>[0]> = {}): void {
    registerNodeType({idname, label, declare, execute, ...extra})
}

stringNode('FunctionNodeInputString', 'String', b => {
    b.output('STRING', 'String')
}, p => p.set('String', p.node.prop<string>('string') ?? ''), {properties: {string: ''}})

stringNode('FunctionNodeInputSpecialCharacters', 'Special Characters', b => {
    b.output('STRING', 'Line Break')
    b.output('STRING', 'Tab')
}, p => {
    p.set('Line Break', '\n')
    p.set('Tab', '\t')
})

// `BLI_strlen_utf8`.
stringNode('FunctionNodeStringLength', 'String Length', b => {
    b.input('STRING', 'String')
    b.output('INT', 'Length')
}, p => p.set('Length', int(codePoints(p.string('String')).length)))

// `str.substr(offset(max(0, a)), offset(max(0, a + b)) - start)` with `BLI_str_utf8_offset_from_index`.
stringNode('FunctionNodeSliceString', 'Slice String', b => {
    b.input('STRING', 'String')
    b.output('STRING', 'String')
    b.input('INT', 'Position')
    b.input('INT', 'Length').min(0).default(10)
}, p => {
    const cps = codePoints(p.string('String'))
    const a = p.int('Position'), n = p.int('Length')
    const start = Math.min(Math.max(0, a), cps.length)
    const end = Math.min(Math.max(0, (a + n) | 0), cps.length)
    p.set('String', cps.slice(start, Math.max(end, start)).join(''))
})

/** `BLI_string_replaceN`: every non-overlapping occurrence, left to right; nothing for an empty `from`. */
function replaceAll(str: string, from: string, to: string): string {
    if (!from) return str
    return str.split(from).join(to)
}

stringNode('FunctionNodeReplaceString', 'Replace String', b => {
    b.input('STRING', 'String')
    b.output('STRING', 'String')
    b.input('STRING', 'Find')
    b.input('STRING', 'Replace')
}, p => p.set('String', replaceAll(p.string('String'), p.string('Find'), p.string('Replace'))))

stringNode('FunctionNodeReverseString', 'Reverse String', b => {
    b.input('STRING', 'String')
    b.output('STRING', 'String')
}, p => p.set('String', codePoints(p.string('String')).reverse().join('')))

/** `StringRef::find_first_not_of` / `find_last_not_of` over bytes. */
stringNode('FunctionNodeTrimString', 'Trim String', b => {
    b.input('STRING', 'String')
    b.output('STRING', 'String')
    b.input('STRING', 'Characters')
    b.input('BOOLEAN', 'Whitespace').default(true)
    b.input('BOOLEAN', 'Start').default(true)
    b.input('BOOLEAN', 'End').default(true)
}, p => {
    const bytes = encoder.encode(p.string('String'))
    const trim = new Set(encoder.encode(p.string('Characters') + (p.bool('Whitespace') ? ' \t\n\r' : '')))
    let start = 0, end = bytes.length
    if (p.bool('Start')) {
        const i = bytes.findIndex(c => !trim.has(c))
        if (i !== -1) start = i
    }
    if (p.bool('End')) {
        let i = bytes.length - 1
        while (i >= 0 && trim.has(bytes[i])) i--
        if (i !== -1) end = i + 1
    }
    // `str.substr(start, end - start)`: an all-trimmed string keeps start 0 and end size (nothing found).
    p.set('String', decoder.decode(bytes.subarray(start, Math.max(start, end))))
})
