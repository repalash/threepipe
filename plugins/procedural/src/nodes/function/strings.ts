/**
 * `std::fixed << std::setprecision(n) << float` (libc++ through `snprintf("%.*f")`, macOS libc): the exact binary
 * value rounded to `n` decimals, ties to even, the sign kept (also for -0 and values rounding to zero).
 */
export function formatFixed(x: number, n: number): string {
    if (Number.isNaN(x)) return 'nan'
    if (!Number.isFinite(x)) return x < 0 ? '-inf' : 'inf'
    const negative = x < 0 || Object.is(x, -0)
    // The exact value as mantissa * 2^exp.
    const view = new DataView(new ArrayBuffer(8))
    view.setFloat64(0, Math.abs(x))
    const hi = view.getUint32(0), lo = view.getUint32(4)
    const biased = (hi >>> 20) & 0x7ff
    let mantissa = (BigInt(hi & 0xfffff) << 32n) | BigInt(lo)
    let exp = biased - 1075
    if (biased === 0) exp = -1074
    else mantissa |= 1n << 52n
    // scaled = mantissa * 2^exp * 10^n, rounded half to even.
    let num = mantissa * 10n ** BigInt(n), den = 1n
    if (exp >= 0) num <<= BigInt(exp)
    else den <<= BigInt(-exp)
    let q = num / den
    const r = num - q * den
    if (r * 2n > den || (r * 2n === den && (q & 1n) === 1n)) q += 1n
    let digits = q.toString()
    if (n > 0) {
        digits = digits.padStart(n + 1, '0')
        digits = `${digits.slice(0, digits.length - n)}.${digits.slice(digits.length - n)}`
    }
    return (negative ? '-' : '') + digits
}

