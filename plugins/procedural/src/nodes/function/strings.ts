/** Code points in the first `bytes` bytes of `s` (`BLI_strnlen_utf8_ex`). */
function charsInBytes(s: Uint8Array, bytes: number): number {
    let n = 0
    for (let i = 0; i < Math.min(bytes, s.length); i++) if ((s[i] & 0xc0) !== 0x80) n++
    return n
}

/** `StringRef::find` / `rfind` over bytes: the byte position or -1. */
function findBytes(text: Uint8Array, token: Uint8Array, from: number, reverse: boolean): number {
    const last = text.length - token.length
    const match = (i: number) => {
        for (let k = 0; k < token.length; k++) if (text[i + k] !== token[k]) return false
        return true
    }
    if (reverse) {
        for (let i = last; i >= 0; i--) if (match(i)) return i
    } else {
        for (let i = from; i <= last; i++) if (match(i)) return i
    }
    return -1
}

