/** Binary search as written (`string_utf8.cc:765`), over the tables' sorted entries. */
function lookup(from: number[], to: number[], wc: number): number {
    if (wc >= from[0] && wc <= from[from.length - 1]) {
        let min = 0, max = from.length - 1
        while (max >= min) {
            const mid = (min + max) >> 1
            if (wc > from[mid]) min = mid + 1
            else if (wc < from[mid]) max = mid - 1
            else return to[mid]
        }
    }
    return wc
}

/** `BLI_str_utf32_char_to_upper` (`string_utf8.cc:680`). */
export function utf32CharToUpper(wc: number): number {
    if (wc < 0xff) {
        if ((wc <= 0x7a && wc >= 0x61) || (wc <= 0xf6 && wc >= 0xe0) || wc >= 0xf8) return wc - 32
        return wc
    }
    if ((wc <= 0x137 && wc >= 0x101) || (wc <= 0x1e95 && wc >= 0x1e01)) return wc & 1 ? wc - 1 : wc
    if ((wc <= 0x586 && wc >= 0x561) || (wc <= 0x10f5 && wc >= 0x10d0)) return wc - 48
    if (wc <= 0x24e9 && wc >= 0x24d0) return wc - 26
    if (wc <= 0xff5a && wc >= 0xff41) return wc - 32
    if (!(wc <= 0x0292 && wc >= 0x00ff) && !(wc <= 0x04f9 && wc >= 0x03ac) && !(wc <= 0x1fe1 && wc >= 0x1e01)) return wc
    return lookup(UPPER_FROM, UPPER_TO, wc)
}

/** `BLI_str_utf32_char_to_lower` (`string_utf8.cc:791`). */
export function utf32CharToLower(wc: number): number {
    if (wc < 0xd8) {
        if ((wc <= 0x5a && wc >= 0x41) || (wc <= 0xd6 && wc >= 0xc0)) return wc + 32
        return wc
    }
    if ((wc <= 0x136 && wc >= 0x100) || (wc <= 0x1e94 && wc >= 0x1e00)) return wc % 2 === 0 ? wc + 1 : wc
    if ((wc <= 0x556 && wc >= 0x531) || (wc <= 0x10c5 && wc >= 0x10a0)) return wc + 48
    if (wc <= 0x24cf && wc >= 0x24b6) return wc + 26
    if (wc <= 0xff3a && wc >= 0xff21) return wc + 32
    if (!(wc <= 0x0216 && wc >= 0x00d8) && !(wc <= 0x04f8 && wc >= 0x0386) && !(wc <= 0x1fe9 && wc >= 0x1e00)) return wc
    return lookup(LOWER_FROM, LOWER_TO, wc)
}

